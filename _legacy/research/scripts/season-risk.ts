/**
 * Turns research/data/backtest.csv (the real risk engine on 5 years of weather) into the small table the
 * processor panel draws: per location and month, the average number of days with Medium or High risk.
 *
 * Run from the project root:   npx tsx research/scripts/season-risk.ts
 * Writes src/data/seasonRisk.ts.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(__dirname, '..');
const CSV = path.join(ROOT, 'data', 'backtest.csv');
const OUT = path.join(ROOT, '..', 'src', 'data', 'seasonRisk.ts');
const THREATS = { 'peacock-spot': 'peacock', 'olive-fly': 'fly' } as const;

const lines = fs.readFileSync(CSV, 'utf8').trim().split(/\r?\n/).slice(1);
const years = new Set<string>();
const days: Record<string, Record<'peacock' | 'fly', number[]>> = {};

for (const line of lines) {
  const [location, , date, threat, , level] = line.split(',');
  const key = THREATS[threat as keyof typeof THREATS];
  if (!key || level === 'Low') continue;
  years.add(date.slice(0, 4));
  days[location] ??= { peacock: Array(12).fill(0), fly: Array(12).fill(0) };
  days[location][key][Number(date.slice(5, 7)) - 1] += 1;
}

const n = years.size;
const round = (x: number) => Math.round((x / n) * 10) / 10;
const table = Object.fromEntries(
  Object.entries(days).map(([loc, d]) => [loc, { peacock: d.peacock.map(round), fly: d.fly.map(round) }]),
);

const out =
  `/** Generated by research/scripts/season-risk.ts from research/data/backtest.csv. Do not edit by hand.\n` +
  ` *  Average days per month with Medium or High risk, over ${[...years].sort()[0]}–${[...years].sort().at(-1)}, from the app's risk engine. */\n` +
  `export const SEASON_RISK_YEARS = ${n};\n` +
  `export const SEASON_RISK: Record<string, { peacock: number[]; fly: number[] }> = ${JSON.stringify(table, null, 2)};\n`;
fs.writeFileSync(OUT, out);
console.log(`Wrote ${OUT} (${Object.keys(table).join(', ')})`);
